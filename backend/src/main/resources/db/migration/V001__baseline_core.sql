-- Baseline core schema (legacy db/schema.sql equivalent).
-- Users & roles, customers, products, policies, premium schedules and payments.

CREATE TABLE user_role (
    role_id         BIGINT PRIMARY KEY,
    role_name       VARCHAR(30)  NOT NULL UNIQUE,
    description     VARCHAR(100),
    security_level  INTEGER      NOT NULL DEFAULT 1
);

CREATE TABLE user_account (
    user_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(30)  NOT NULL UNIQUE,
    password_hash    VARCHAR(100) NOT NULL,
    full_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(120),
    role_id          BIGINT       NOT NULL REFERENCES user_role (role_id),
    branch_cd        VARCHAR(10),
    status           VARCHAR(1)   NOT NULL DEFAULT 'A',      -- A active, L locked, D disabled
    failed_logins    INTEGER      NOT NULL DEFAULT 0,
    last_login_dt    TIMESTAMP,
    pwd_changed_dt   TIMESTAMP,
    created_dt       TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_status CHECK (status IN ('A','L','D'))
);

CREATE TABLE customer (
    customer_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_no      VARCHAR(20)  NOT NULL UNIQUE,
    customer_type    VARCHAR(10)  NOT NULL DEFAULT 'INDIVIDUAL',
    first_name       VARCHAR(60),
    last_name        VARCHAR(60),
    company_name     VARCHAR(120),
    national_id      VARCHAR(30),
    date_of_birth    DATE,
    gender           VARCHAR(1),
    email            VARCHAR(120),
    phone            VARCHAR(30),
    occupation_code  VARCHAR(20),
    status           VARCHAR(1)   NOT NULL DEFAULT 'A',
    created_dt       TIMESTAMP    NOT NULL DEFAULT now(),
    created_by       VARCHAR(30),
    updated_dt       TIMESTAMP,
    CONSTRAINT ck_customer_type CHECK (customer_type IN ('INDIVIDUAL','CORPORATE'))
);

CREATE TABLE customer_address (
    address_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT       NOT NULL REFERENCES customer (customer_id),
    address_type    VARCHAR(10)  NOT NULL DEFAULT 'HOME',
    line1           VARCHAR(120) NOT NULL,
    line2           VARCHAR(120),
    city            VARCHAR(60)  NOT NULL,
    state           VARCHAR(60),
    postal_code     VARCHAR(20),
    country         VARCHAR(60)  NOT NULL DEFAULT 'USA',
    primary_flag    VARCHAR(1)   NOT NULL DEFAULT 'N',
    effective_from  DATE         NOT NULL DEFAULT CURRENT_DATE,
    effective_to    DATE
);
CREATE INDEX idx_addr_customer ON customer_address (customer_id);

CREATE TABLE insurance_product (
    product_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code      VARCHAR(20)   NOT NULL UNIQUE,
    product_name      VARCHAR(100)  NOT NULL,
    line_of_business  VARCHAR(10)   NOT NULL,
    description       VARCHAR(500),
    base_rate         NUMERIC(10,4) NOT NULL DEFAULT 1.0000,
    status            VARCHAR(1)    NOT NULL DEFAULT 'A',
    created_dt        TIMESTAMP     NOT NULL DEFAULT now(),
    updated_dt        TIMESTAMP,
    CONSTRAINT ck_product_lob CHECK (line_of_business IN ('LIFE','HEALTH','MOTOR','HOME'))
);

CREATE TABLE policy (
    policy_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_no            VARCHAR(20)   NOT NULL UNIQUE,
    customer_id          BIGINT        NOT NULL REFERENCES customer (customer_id),
    product_id           BIGINT        NOT NULL REFERENCES insurance_product (product_id),
    status               VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    sum_insured          NUMERIC(14,2) NOT NULL,
    term_months          INTEGER       NOT NULL DEFAULT 12,
    payment_frequency    VARCHAR(10)   NOT NULL DEFAULT 'ANNUAL',
    risk_class           VARCHAR(4)    NOT NULL DEFAULT 'STD',
    smoker_flag          VARCHAR(1)    NOT NULL DEFAULT 'N',
    occupation_code      VARCHAR(20),
    medical_codes        VARCHAR(200),
    annual_premium       NUMERIC(14,2),
    installment_premium  NUMERIC(14,2),
    start_dt             DATE          NOT NULL,
    end_dt               DATE          NOT NULL,
    issue_dt             DATE,
    branch_cd            VARCHAR(10),
    version_no           INTEGER       NOT NULL DEFAULT 1,
    created_by           VARCHAR(30),
    created_dt           TIMESTAMP     NOT NULL DEFAULT now(),
    updated_dt           TIMESTAMP,
    CONSTRAINT ck_policy_freq CHECK (payment_frequency IN ('ANNUAL','SEMI','QUARTERLY','MONTHLY')),
    CONSTRAINT ck_policy_risk CHECK (risk_class IN ('STD','PREF','SUB','HIGH'))
);
CREATE INDEX idx_policy_customer ON policy (customer_id);
CREATE INDEX idx_policy_status ON policy (status);

CREATE TABLE policy_version (
    version_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id       BIGINT        NOT NULL REFERENCES policy (policy_id),
    version_no      INTEGER       NOT NULL,
    effective_dt    DATE          NOT NULL,
    sum_insured     NUMERIC(14,2) NOT NULL,
    annual_premium  NUMERIC(14,2),
    change_type     VARCHAR(20)   NOT NULL,
    change_note     VARCHAR(300),
    created_by      VARCHAR(30),
    created_dt      TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uq_policy_version UNIQUE (policy_id, version_no)
);

CREATE TABLE premium_schedule (
    schedule_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id       BIGINT        NOT NULL REFERENCES policy (policy_id),
    installment_no  INTEGER       NOT NULL,
    due_dt          DATE          NOT NULL,
    amount_due      NUMERIC(14,2) NOT NULL,
    amount_paid     NUMERIC(14,2) NOT NULL DEFAULT 0,
    status          VARCHAR(10)   NOT NULL DEFAULT 'DUE',
    paid_dt         DATE,
    CONSTRAINT ck_sched_status CHECK (status IN ('DUE','PARTIAL','PAID','OVERDUE','WAIVED','CANCELLED'))
);
CREATE INDEX idx_sched_policy ON premium_schedule (policy_id, installment_no);
CREATE INDEX idx_sched_due ON premium_schedule (status, due_dt);

CREATE TABLE premium_payment (
    payment_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id        BIGINT        NOT NULL REFERENCES policy (policy_id),
    amount           NUMERIC(14,2) NOT NULL,
    method           VARCHAR(10)   NOT NULL,
    instrument_ref   VARCHAR(40),
    status           VARCHAR(10)   NOT NULL,
    payment_dt       TIMESTAMP     NOT NULL DEFAULT now(),
    created_by       VARCHAR(30),
    CONSTRAINT ck_pay_method CHECK (method IN ('CARD','BANK','CASH','CHEQUE'))
);
CREATE INDEX idx_payment_policy ON premium_payment (policy_id);

CREATE TABLE audit_log (
    audit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor        VARCHAR(30)  NOT NULL,
    action       VARCHAR(40)  NOT NULL,
    entity_type  VARCHAR(30),
    entity_id    BIGINT,
    detail       VARCHAR(1000),
    created_dt   TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_dt ON audit_log (created_dt);
