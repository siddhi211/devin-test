-- Claims module (legacy migrations 040-049): catalogue, sequence, claim, history, notes,
-- documents, assessments, risk flags, settlements, payout events.

CREATE TABLE claim_category (
    category_code      VARCHAR(20)   PRIMARY KEY,
    line_of_business   VARCHAR(10)   NOT NULL,
    description        VARCHAR(100)  NOT NULL,
    waiting_days       INTEGER       NOT NULL DEFAULT 0,
    reporting_days     INTEGER       NOT NULL DEFAULT 30,
    sla_days           INTEGER       NOT NULL DEFAULT 14,
    deductible         NUMERIC(14,2) NOT NULL DEFAULT 0,
    coverage_pct       NUMERIC(6,2)  NOT NULL DEFAULT 100,
    excluded_causes    VARCHAR(200),
    active             VARCHAR(1)    NOT NULL DEFAULT 'Y'
);

CREATE TABLE claim_sequence (
    seq_year    INTEGER   PRIMARY KEY,
    next_val    INTEGER   NOT NULL DEFAULT 0,
    updated_dt  TIMESTAMP
);

CREATE TABLE claim (
    claim_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_no              VARCHAR(20)   NOT NULL UNIQUE,
    policy_id             BIGINT        NOT NULL REFERENCES policy (policy_id),
    customer_id           BIGINT        NOT NULL REFERENCES customer (customer_id),
    category_code         VARCHAR(20)   NOT NULL REFERENCES claim_category (category_code),
    subtype_code          VARCHAR(30),
    incident_dt           DATE          NOT NULL,
    reported_dt           DATE          NOT NULL,
    description           VARCHAR(1000) NOT NULL,
    claimed_amount        NUMERIC(14,2) NOT NULL,
    assessed_amount       NUMERIC(14,2),
    approved_amount       NUMERIC(14,2),
    settled_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    status                VARCHAR(20)   NOT NULL DEFAULT 'REGISTERED',
    priority              VARCHAR(6)    NOT NULL DEFAULT 'NORMAL',
    assigned_adjuster_id  BIGINT        REFERENCES user_account (user_id),
    reopen_count          INTEGER       NOT NULL DEFAULT 0,
    sla_due_dt            DATE,
    sla_breached          VARCHAR(1)    NOT NULL DEFAULT 'N',
    fraud_score           INTEGER       NOT NULL DEFAULT 0,
    decision_reason       VARCHAR(300),
    findings              VARCHAR(500),
    decided_dt            TIMESTAMP,
    created_by            VARCHAR(30)   NOT NULL,
    created_dt            TIMESTAMP     NOT NULL DEFAULT now(),
    updated_dt            TIMESTAMP,
    -- PARTIALLY_APPROVED is stored as 'PARTIAL' for compatibility with legacy reporting.
    CONSTRAINT ck_claim_status CHECK (status IN
        ('REGISTERED','ASSIGNED','UNDER_INVESTIGATION','PENDING_INFO','ASSESSED','PENDING_APPROVAL',
         'APPROVED','PARTIAL','REJECTED','SETTLED','CLOSED','REOPENED'))
);
CREATE INDEX idx_claim_policy ON claim (policy_id);
CREATE INDEX idx_claim_status ON claim (status, sla_due_dt);
CREATE INDEX idx_claim_adjuster ON claim (assigned_adjuster_id, status);
CREATE INDEX idx_claim_incident ON claim (incident_dt);

CREATE TABLE claim_status_history (
    history_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     BIGINT       NOT NULL REFERENCES claim (claim_id),
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    reason       VARCHAR(300),
    actor        VARCHAR(30)  NOT NULL,
    changed_dt   TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_clh_claim ON claim_status_history (claim_id, changed_dt);

CREATE TABLE claim_note (
    note_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT        NOT NULL REFERENCES claim (claim_id),
    note_type   VARCHAR(15)   NOT NULL DEFAULT 'NOTE',   -- NOTE, INVESTIGATION, SYSTEM
    note_text   VARCHAR(2000) NOT NULL,
    author      VARCHAR(30)   NOT NULL,
    created_dt  TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_claim_note_claim ON claim_note (claim_id);

CREATE TABLE claim_document (
    document_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     BIGINT       NOT NULL REFERENCES claim (claim_id),
    doc_type     VARCHAR(20)  NOT NULL,
    file_name    VARCHAR(200) NOT NULL,
    uploaded_by  VARCHAR(30)  NOT NULL,
    uploaded_dt  TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE claim_assessment (
    assessment_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id          BIGINT        NOT NULL REFERENCES claim (claim_id),
    claimed_amount    NUMERIC(14,2) NOT NULL,
    excluded_amount   NUMERIC(14,2) NOT NULL DEFAULT 0,
    depreciation_pct  NUMERIC(6,2)  NOT NULL DEFAULT 0,
    depreciation_amt  NUMERIC(14,2) NOT NULL DEFAULT 0,
    salvage_amount    NUMERIC(14,2) NOT NULL DEFAULT 0,
    deductible        NUMERIC(14,2) NOT NULL DEFAULT 0,
    coinsurance_pct   NUMERIC(6,2)  NOT NULL DEFAULT 0,
    net_amount        NUMERIC(14,2) NOT NULL,
    fraud_score       INTEGER       NOT NULL DEFAULT 0,
    calc_trace        TEXT,
    assessed_by       VARCHAR(30)   NOT NULL,
    assessed_dt       TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_assessment_claim ON claim_assessment (claim_id);

CREATE TABLE claim_risk_flag (
    flag_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT       NOT NULL REFERENCES claim (claim_id),
    flag_code   VARCHAR(24)  NOT NULL,
    score       INTEGER      NOT NULL,
    detail      VARCHAR(200),
    raised_by   VARCHAR(30)  NOT NULL,
    raised_dt   TIMESTAMP    NOT NULL DEFAULT now(),
    cleared_dt  TIMESTAMP,
    cleared_by  VARCHAR(30)
);
CREATE INDEX idx_crf_claim ON claim_risk_flag (claim_id, cleared_dt);

CREATE TABLE claim_settlement (
    settlement_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id          BIGINT        NOT NULL REFERENCES claim (claim_id),
    payout_seq        INTEGER       NOT NULL,
    method            VARCHAR(10)   NOT NULL,   -- TRANSFER, CHECK, CASH
    payee_name        VARCHAR(100)  NOT NULL,
    gross_amount      NUMERIC(14,2) NOT NULL,
    net_amount        NUMERIC(14,2) NOT NULL,
    status            VARCHAR(10)   NOT NULL DEFAULT 'PAID',
    payout_ref        VARCHAR(40)   NOT NULL,
    paid_by           VARCHAR(30)   NOT NULL,
    paid_dt           TIMESTAMP     NOT NULL DEFAULT now(),
    reversed_dt       TIMESTAMP,
    reversed_by       VARCHAR(30),
    reversal_reason   VARCHAR(200),
    CONSTRAINT uq_settlement_seq UNIQUE (claim_id, payout_seq),
    CONSTRAINT ck_settlement_status CHECK (status IN ('PAID','REVERSED'))
);

CREATE TABLE claim_payout_event (
    event_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id         BIGINT        NOT NULL REFERENCES claim (claim_id),
    event_type       VARCHAR(10)   NOT NULL,   -- PAID, REVERSED, ADJUSTED
    amount           NUMERIC(14,2) NOT NULL,
    payout_ref       VARCHAR(40),
    actor            VARCHAR(30)   NOT NULL,
    detail           VARCHAR(200),
    ledger_ref_type  VARCHAR(10),
    ledger_ref_id    BIGINT,
    event_dt         TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_cpe_claim ON claim_payout_event (claim_id, event_dt);
