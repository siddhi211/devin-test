-- Workflow & notification module (legacy migrations 050-059): table-driven approval engine,
-- four-eyes control, task queue, delegation, notification templates and outbox.

CREATE TABLE workflow_definition (
    def_code      VARCHAR(30)  PRIMARY KEY,
    subject_type  VARCHAR(20)  NOT NULL,   -- CLAIM, UW_REFERRAL, CANCELLATION, REFUND, RENEWAL_EXCEPTION
    description   VARCHAR(200) NOT NULL,
    status        VARCHAR(1)   NOT NULL DEFAULT 'A',
    four_eyes     VARCHAR(1)   NOT NULL DEFAULT 'N',   -- N none, Y requester may not approve, S strict separation
    sla_hours     INTEGER      NOT NULL DEFAULT 48,
    CONSTRAINT ck_wd_four_eyes CHECK (four_eyes IN ('N','Y','S'))
);

CREATE TABLE workflow_step (
    step_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    def_code    VARCHAR(30)   NOT NULL REFERENCES workflow_definition (def_code),
    step_no     INTEGER       NOT NULL,
    step_name   VARCHAR(60)   NOT NULL,
    role_code   VARCHAR(30)   NOT NULL,
    min_amount  NUMERIC(14,2) NOT NULL DEFAULT 0,   -- step applies when subject amount >= min_amount
    CONSTRAINT uq_wf_step UNIQUE (def_code, step_no)
);

CREATE TABLE workflow_delegation (
    delegation_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_username  VARCHAR(30) NOT NULL,
    to_username    VARCHAR(30) NOT NULL,
    start_dt       DATE        NOT NULL,
    end_dt         DATE        NOT NULL,
    created_dt     TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE TABLE workflow_instance (
    instance_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    def_code      VARCHAR(30)   NOT NULL REFERENCES workflow_definition (def_code),
    subject_type  VARCHAR(20)   NOT NULL,
    subject_id    BIGINT        NOT NULL,
    subject_ref   VARCHAR(40),
    amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    status        VARCHAR(10)   NOT NULL DEFAULT 'OPEN',
    active_flag   VARCHAR(1)    NOT NULL DEFAULT 'Y',
    current_step  INTEGER,
    requested_by  VARCHAR(30)   NOT NULL,
    created_dt    TIMESTAMP     NOT NULL DEFAULT now(),
    completed_dt  TIMESTAMP,
    CONSTRAINT ck_wfi_status CHECK (status IN ('OPEN','APPROVED','REJECTED','CANCELLED'))
);
-- At most one active workflow per subject.
CREATE UNIQUE INDEX uq_wfi_open ON workflow_instance (subject_type, subject_id) WHERE active_flag = 'Y';

CREATE TABLE workflow_task (
    task_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id    BIGINT       NOT NULL REFERENCES workflow_instance (instance_id),
    step_no        INTEGER      NOT NULL,
    step_name      VARCHAR(60)  NOT NULL,
    role_code      VARCHAR(30)  NOT NULL,
    assigned_user  VARCHAR(30),
    status         VARCHAR(10)  NOT NULL DEFAULT 'OPEN',
    decision       VARCHAR(10),
    decision_note  VARCHAR(500),
    decided_by     VARCHAR(30),
    acting_for     VARCHAR(30),
    sla_due_dt     TIMESTAMP    NOT NULL,
    sla_breached   VARCHAR(1)   NOT NULL DEFAULT 'N',
    created_dt     TIMESTAMP    NOT NULL DEFAULT now(),
    decided_dt     TIMESTAMP,
    CONSTRAINT ck_wft_status CHECK (status IN ('OPEN','CLAIMED','DONE','CANCELLED')),
    CONSTRAINT ck_wft_decision CHECK (decision IS NULL OR decision IN ('APPROVE','REJECT'))
);
CREATE INDEX idx_wft_queue ON workflow_task (status, role_code);
CREATE INDEX idx_wft_instance ON workflow_task (instance_id);

CREATE TABLE workflow_history (
    history_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id  BIGINT       NOT NULL REFERENCES workflow_instance (instance_id),
    event_type   VARCHAR(20)  NOT NULL,
    actor        VARCHAR(30)  NOT NULL,
    detail       VARCHAR(500),
    created_dt   TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_wfh_instance ON workflow_history (instance_id);

CREATE TABLE notification_template (
    template_code  VARCHAR(40)  PRIMARY KEY,
    channel        VARCHAR(10)  NOT NULL,
    subject_tpl    VARCHAR(200),
    body_tpl       VARCHAR(2000) NOT NULL
);

CREATE TABLE notification_outbox (
    outbox_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_code    VARCHAR(40),
    channel          VARCHAR(10)   NOT NULL,   -- EMAIL, SMS, INAPP
    recipient_addr   VARCHAR(120)  NOT NULL,
    subject          VARCHAR(200),
    body             VARCHAR(2000) NOT NULL,
    status           VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    attempts         INTEGER       NOT NULL DEFAULT 0,
    max_attempts     INTEGER       NOT NULL DEFAULT 4,
    dedup_key        VARCHAR(100),
    ref_type         VARCHAR(20),
    ref_id           BIGINT,
    next_attempt_dt  TIMESTAMP     NOT NULL DEFAULT now(),
    last_error       VARCHAR(200),
    created_dt       TIMESTAMP     NOT NULL DEFAULT now(),
    sent_dt          TIMESTAMP,
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING','SENT','FAILED','DEAD')),
    CONSTRAINT uq_no_dedup UNIQUE (dedup_key)
);
CREATE INDEX idx_outbox_due ON notification_outbox (status, next_attempt_dt);
