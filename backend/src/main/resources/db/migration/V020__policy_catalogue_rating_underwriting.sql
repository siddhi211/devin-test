-- Policy & underwriting module (legacy migrations 020-029): product catalogue/versioning,
-- eligibility rules, rating engine tables, underwriting tables, status history, endorsements.

ALTER TABLE insurance_product
    ADD COLUMN min_age          INTEGER       NOT NULL DEFAULT 18,
    ADD COLUMN max_age          INTEGER       NOT NULL DEFAULT 70,
    ADD COLUMN min_sum_insured  NUMERIC(14,2) NOT NULL DEFAULT 1000,
    ADD COLUMN max_sum_insured  NUMERIC(14,2) NOT NULL DEFAULT 5000000,
    ADD COLUMN min_term_months  INTEGER       NOT NULL DEFAULT 12,
    ADD COLUMN max_term_months  INTEGER       NOT NULL DEFAULT 360,
    ADD COLUMN version_no       INTEGER       NOT NULL DEFAULT 1,
    ADD CONSTRAINT ck_product_status CHECK (status IN ('A','D','S','R'));

CREATE TABLE product_version (
    product_version_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT      NOT NULL REFERENCES insurance_product (product_id),
    version_no          INTEGER     NOT NULL,
    snapshot            TEXT        NOT NULL,
    created_by          VARCHAR(30),
    created_dt          TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uq_product_version UNIQUE (product_id, version_no)
);

CREATE TABLE product_eligibility_rule (
    rule_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL REFERENCES insurance_product (product_id),
    rule_type   VARCHAR(20)  NOT NULL,   -- MAX_OPEN_CLAIMS, BLOCKED_STATUS, KYC_REQUIRED, MIN_AGE, MAX_AGE
    rule_value  VARCHAR(40),
    message     VARCHAR(200) NOT NULL,
    active      VARCHAR(1)   NOT NULL DEFAULT 'Y'
);

CREATE TABLE rate_base (
    rate_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT        NOT NULL REFERENCES insurance_product (product_id),
    age_from       INTEGER       NOT NULL,
    age_to         INTEGER       NOT NULL,
    risk_class     VARCHAR(4)    NOT NULL,
    rate_per_1000  NUMERIC(10,4) NOT NULL,
    CONSTRAINT ck_rate_risk CHECK (risk_class IN ('STD','PREF','SUB','HIGH'))
);
CREATE INDEX idx_rate_base_lookup ON rate_base (product_id, risk_class, age_from);

CREATE TABLE rating_rule (
    rule_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT        NOT NULL REFERENCES insurance_product (product_id),
    rule_order       INTEGER       NOT NULL,
    rule_name        VARCHAR(60)   NOT NULL,
    rule_kind        VARCHAR(10)   NOT NULL,  -- LOADING, DISCOUNT, SURCHARGE, FEE, TAX
    condition_field  VARCHAR(20)   NOT NULL,  -- ANY, AGE, SMOKER, SUM_INSURED, TERM, FREQUENCY, OCC_CLASS
    condition_op     VARCHAR(4)    NOT NULL,  -- EQ, GT, GTE, LT, LTE, ANY
    condition_value  VARCHAR(40),
    amount_type      VARCHAR(4)    NOT NULL,  -- PCT, FLAT
    amount           NUMERIC(12,4) NOT NULL,
    active           VARCHAR(1)    NOT NULL DEFAULT 'Y',
    CONSTRAINT ck_rule_kind CHECK (rule_kind IN ('LOADING','DISCOUNT','SURCHARGE','FEE','TAX'))
);

CREATE TABLE rounding_rule (
    product_id     BIGINT        PRIMARY KEY REFERENCES insurance_product (product_id),
    scale_digits   INTEGER       NOT NULL DEFAULT 2,
    rounding_mode  VARCHAR(10)   NOT NULL DEFAULT 'HALF_UP',
    min_premium    NUMERIC(14,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_rounding_mode CHECK (rounding_mode IN ('HALF_UP','DOWN','UP','NEAREST_5'))
);

CREATE TABLE premium_quote_log (
    quote_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT        NOT NULL REFERENCES insurance_product (product_id),
    customer_id     BIGINT        REFERENCES customer (customer_id),
    input_summary   VARCHAR(500)  NOT NULL,
    trace           TEXT,
    annual_premium  NUMERIC(14,2) NOT NULL,
    created_by      VARCHAR(30),
    created_dt      TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE uw_occupation (
    occ_code     VARCHAR(20)  PRIMARY KEY,
    description  VARCHAR(100) NOT NULL,
    risk_class   INTEGER      NOT NULL,
    points       INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT ck_occ_class CHECK (risk_class BETWEEN 1 AND 4)
);

CREATE TABLE uw_medical_code (
    med_code      VARCHAR(20)  PRIMARY KEY,
    description   VARCHAR(100) NOT NULL,
    points        INTEGER      NOT NULL DEFAULT 0,
    decline_flag  VARCHAR(1)   NOT NULL DEFAULT 'N'
);

CREATE TABLE uw_rule (
    rule_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code  VARCHAR(30)   NOT NULL UNIQUE,
    field      VARCHAR(20)   NOT NULL,   -- AGE, SUM_INSURED, SMOKER, OCC_CLASS, TERM
    op         VARCHAR(4)    NOT NULL,
    threshold  VARCHAR(40)   NOT NULL,
    action     VARCHAR(10)   NOT NULL,   -- REFER, DECLINE, POINTS
    points     INTEGER       NOT NULL DEFAULT 0,
    message    VARCHAR(200)  NOT NULL,
    active     VARCHAR(1)    NOT NULL DEFAULT 'Y'
);

CREATE TABLE uw_authority (
    level_no         INTEGER       PRIMARY KEY,
    description      VARCHAR(60)   NOT NULL,
    max_sum_insured  NUMERIC(14,2) NOT NULL
);

CREATE TABLE uw_reviewer (
    user_id   BIGINT  PRIMARY KEY REFERENCES user_account (user_id),
    level_no  INTEGER NOT NULL REFERENCES uw_authority (level_no)
);

CREATE TABLE uw_decision (
    decision_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id     BIGINT       NOT NULL REFERENCES policy (policy_id),
    total_points  INTEGER      NOT NULL,
    outcome       VARCHAR(12)  NOT NULL,   -- AUTO_APPROVE, REFER, DECLINE, APPROVED, DECLINED
    findings      TEXT,
    decided_by    VARCHAR(30)  NOT NULL,
    note          VARCHAR(300),
    decided_dt    TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_uw_decision_policy ON uw_decision (policy_id);

ALTER TABLE policy
    ADD COLUMN lapse_dt       DATE,
    ADD COLUMN renewal_count  INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_policy_status CHECK (status IN
        ('DRAFT','SUBMITTED','PENDING_UW','UW_APPROVED','ACTIVE','GRACE','LAPSED',
         'DECLINED','WITHDRAWN','CANCELLED','EXPIRED'));

CREATE TABLE policy_status_history (
    history_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id    BIGINT       NOT NULL REFERENCES policy (policy_id),
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    reason       VARCHAR(300),
    actor        VARCHAR(30)  NOT NULL,
    changed_dt   TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_psh_policy ON policy_status_history (policy_id, changed_dt);

CREATE TABLE policy_endorsement (
    endorsement_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id         BIGINT        NOT NULL REFERENCES policy (policy_id),
    endorsement_type  VARCHAR(20)   NOT NULL,   -- SUM_INSURED, ADDRESS, BENEFICIARY, OTHER
    description       VARCHAR(300)  NOT NULL,
    old_value         VARCHAR(100),
    new_value         VARCHAR(100),
    adjustment        NUMERIC(14,2) NOT NULL DEFAULT 0,
    effective_dt      DATE          NOT NULL,
    created_by        VARCHAR(30)   NOT NULL,
    created_dt        TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_endorsement_policy ON policy_endorsement (policy_id);
