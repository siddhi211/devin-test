-- Lifecycle module (legacy migrations 060-069): renewals, policy lifecycle flags, cancellations,
-- cancel reasons, batch job definitions/runs/locks/item errors.

CREATE TABLE policy_lifecycle (
    policy_id      BIGINT       PRIMARY KEY REFERENCES policy (policy_id),
    auto_renew     VARCHAR(1)   NOT NULL DEFAULT 'N',
    ncb_years      INTEGER      NOT NULL DEFAULT 0,
    last_claim_dt  DATE,
    updated_dt     TIMESTAMP    NOT NULL DEFAULT now(),
    updated_by     VARCHAR(30)
);

CREATE TABLE renewal_request (
    renewal_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id         BIGINT        NOT NULL REFERENCES policy (policy_id),
    status            VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    renewal_start_dt  DATE          NOT NULL,
    offer_dt          DATE,
    offer_expires_dt  DATE,
    current_premium   NUMERIC(14,2) NOT NULL,
    base_premium      NUMERIC(14,2),
    ncb_pct           NUMERIC(6,2)  NOT NULL DEFAULT 0,
    claims_load_pct   NUMERIC(6,2)  NOT NULL DEFAULT 0,
    offered_premium   NUMERIC(14,2),
    reuw_flag         VARCHAR(1)    NOT NULL DEFAULT 'N',
    reuw_reason       VARCHAR(200),
    premium_engine    VARCHAR(20),
    new_version_no    INTEGER,
    auto_issued       VARCHAR(1)    NOT NULL DEFAULT 'N',
    notes             VARCHAR(500),
    decided_by        VARCHAR(30),
    decided_dt        TIMESTAMP,
    created_by        VARCHAR(30)   NOT NULL,
    created_dt        TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_renewal_status CHECK (status IN
        ('PENDING','OFFERED','REFERRED','ACCEPTED','RENEWED','DECLINED','LAPSED'))
);
CREATE INDEX idx_renewal_policy ON renewal_request (policy_id, status);

CREATE TABLE lc_cancel_reason (
    reason_code  VARCHAR(20)  PRIMARY KEY,
    description  VARCHAR(100) NOT NULL,
    cancel_type  VARCHAR(10)  NOT NULL,
    refundable   VARCHAR(1)   NOT NULL DEFAULT 'Y',
    active       VARCHAR(1)   NOT NULL DEFAULT 'Y'
);

CREATE TABLE cancellation_request (
    cancellation_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id           BIGINT        NOT NULL REFERENCES policy (policy_id),
    cancel_type         VARCHAR(10)   NOT NULL,   -- INSURED, INSURER, NONPAY
    reason_code         VARCHAR(20)   NOT NULL REFERENCES lc_cancel_reason (reason_code),
    requested_dt        DATE          NOT NULL,
    effective_dt        DATE          NOT NULL,
    cooling_off         VARCHAR(1)    NOT NULL DEFAULT 'N',
    refund_method       VARCHAR(10)   NOT NULL,   -- PRORATA, SHORTRATE, FULL, NONE
    premium_paid        NUMERIC(14,2) NOT NULL DEFAULT 0,
    earned_premium      NUMERIC(14,2) NOT NULL DEFAULT 0,
    cancel_fee          NUMERIC(14,2) NOT NULL DEFAULT 0,
    refund_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    arrears             NUMERIC(14,2) NOT NULL DEFAULT 0,
    open_claims         INTEGER       NOT NULL DEFAULT 0,
    status              VARCHAR(16)   NOT NULL,
    approval_level      INTEGER       NOT NULL DEFAULT 0,
    override_flag       VARCHAR(1)    NOT NULL DEFAULT 'N',
    prior_status        VARCHAR(20),
    reinstate_until_dt  DATE,
    reinstated_dt       TIMESTAMP,
    reinstated_by       VARCHAR(30),
    refund_id           BIGINT        REFERENCES billing_refund (refund_id),
    notes               VARCHAR(500),
    requested_by        VARCHAR(30)   NOT NULL,
    decided_by          VARCHAR(30),
    decided_dt          TIMESTAMP,
    created_dt          TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_cancel_type CHECK (cancel_type IN ('INSURED','INSURER','NONPAY')),
    CONSTRAINT ck_cancel_method CHECK (refund_method IN ('PRORATA','SHORTRATE','FULL','NONE')),
    CONSTRAINT ck_cancel_status CHECK (status IN
        ('PENDING_APPROVAL','APPROVED','REJECTED','COMPLETED','REINSTATED'))
);
CREATE INDEX idx_cancel_policy ON cancellation_request (policy_id);

CREATE TABLE batch_job_def (
    job_name         VARCHAR(40)  PRIMARY KEY,
    description      VARCHAR(200),
    schedule_type    VARCHAR(10)  NOT NULL DEFAULT 'MANUAL',   -- MANUAL, DAILY, EVERY, WEEKLY
    schedule_spec    VARCHAR(40),                              -- HH:mm | minutes | DAY HH:mm
    enabled          VARCHAR(1)   NOT NULL DEFAULT 'Y',
    run_order        INTEGER      NOT NULL DEFAULT 100,
    max_runtime_min  INTEGER      NOT NULL DEFAULT 60,
    default_params   VARCHAR(300),
    updated_dt       TIMESTAMP,
    updated_by       VARCHAR(30)
);

CREATE TABLE batch_job_run (
    run_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name         VARCHAR(40)  NOT NULL,
    status           VARCHAR(10)  NOT NULL,   -- RUNNING, SUCCESS, PARTIAL, FAILED
    triggered_by     VARCHAR(30)  NOT NULL,
    as_of_dt         DATE         NOT NULL,
    started_dt       TIMESTAMP    NOT NULL DEFAULT now(),
    ended_dt         TIMESTAMP,
    items_processed  INTEGER      NOT NULL DEFAULT 0,
    items_failed     INTEGER      NOT NULL DEFAULT 0,
    message          VARCHAR(1000)
);
CREATE INDEX idx_bjr_job ON batch_job_run (job_name, started_dt);

CREATE TABLE batch_job_lock (
    job_name    VARCHAR(40)  PRIMARY KEY,
    owner_id    VARCHAR(80)  NOT NULL,
    acquired_dt TIMESTAMP    NOT NULL,
    expires_dt  TIMESTAMP    NOT NULL
);

CREATE TABLE batch_item_error (
    error_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      BIGINT       NOT NULL REFERENCES batch_job_run (run_id),
    item_key    VARCHAR(60)  NOT NULL,
    error_text  VARCHAR(1000) NOT NULL,
    created_dt  TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_bie_run ON batch_item_error (run_id);
