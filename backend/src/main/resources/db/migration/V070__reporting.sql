-- Reporting & reconciliation module (legacy migrations 070-079).

CREATE TABLE report_run (
    run_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_code  VARCHAR(40)  NOT NULL,
    params       VARCHAR(1000),
    output_fmt   VARCHAR(10)  NOT NULL DEFAULT 'JSON',
    row_count    INTEGER      NOT NULL DEFAULT 0,
    duration_ms  BIGINT       NOT NULL DEFAULT 0,
    run_by       VARCHAR(30)  NOT NULL,
    run_dt       TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_run ON report_run (report_code, run_dt);

CREATE TABLE saved_filter (
    filter_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(30)   NOT NULL,
    report_code  VARCHAR(40)   NOT NULL,
    filter_name  VARCHAR(60)   NOT NULL,
    params       VARCHAR(1000) NOT NULL,
    created_dt   TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uq_saved_filter UNIQUE (username, filter_name)
);

CREATE TABLE reconciliation_discrepancy (
    discrepancy_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_code      VARCHAR(30)   NOT NULL,
    entity_type     VARCHAR(20)   NOT NULL,
    entity_id       BIGINT        NOT NULL,
    detail          VARCHAR(500)  NOT NULL,
    amount          NUMERIC(14,2),
    status          VARCHAR(10)   NOT NULL DEFAULT 'OPEN',
    detected_dt     TIMESTAMP     NOT NULL DEFAULT now(),
    resolved_dt     TIMESTAMP,
    resolved_by     VARCHAR(30),
    resolution_note VARCHAR(300),
    CONSTRAINT ck_disc_status CHECK (status IN ('OPEN','RESOLVED'))
);
CREATE UNIQUE INDEX uq_disc_open ON reconciliation_discrepancy (check_code, entity_type, entity_id) WHERE status = 'OPEN';

CREATE TABLE rpt_policy_monthly (
    period_ym       VARCHAR(7)    NOT NULL,
    product_code    VARCHAR(20)   NOT NULL,
    branch_cd       VARCHAR(10)   NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    policy_count    INTEGER       NOT NULL,
    sum_insured     NUMERIC(18,2) NOT NULL,
    annual_premium  NUMERIC(18,2) NOT NULL,
    refreshed_dt    TIMESTAMP     NOT NULL DEFAULT now(),
    PRIMARY KEY (period_ym, product_code, branch_cd, status)
);

CREATE TABLE rpt_premium_ageing (
    as_of_dt      DATE          NOT NULL,
    product_code  VARCHAR(20)   NOT NULL,
    bucket        VARCHAR(10)   NOT NULL,   -- CURRENT, 1-30, 31-60, 61-90, 90+
    item_count    INTEGER       NOT NULL,
    outstanding   NUMERIC(18,2) NOT NULL,
    refreshed_dt  TIMESTAMP     NOT NULL DEFAULT now(),
    PRIMARY KEY (as_of_dt, product_code, bucket)
);

CREATE TABLE rpt_refresh_log (
    refresh_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name   VARCHAR(40)  NOT NULL,
    row_count    INTEGER      NOT NULL,
    duration_ms  BIGINT       NOT NULL,
    refreshed_by VARCHAR(30)  NOT NULL,
    refreshed_dt TIMESTAMP    NOT NULL DEFAULT now()
);
