-- Billing module (legacy migrations 030-039): idempotent payments, allocations, double-entry
-- journal, receipts, credits, retry queue, product config, refunds, late fees, lapse log.

ALTER TABLE premium_schedule
    ADD COLUMN late_fee        NUMERIC(14,2) NOT NULL DEFAULT 0,
    ADD COLUMN late_fee_paid   NUMERIC(14,2) NOT NULL DEFAULT 0,
    ADD COLUMN retry_count     INTEGER       NOT NULL DEFAULT 0,
    ADD COLUMN failure_reason  VARCHAR(100);

ALTER TABLE premium_payment
    ADD COLUMN idempotency_key  VARCHAR(64),
    ADD COLUMN gateway_code     VARCHAR(20),
    ADD COLUMN gateway_txn_ref  VARCHAR(40),
    ADD COLUMN failure_reason   VARCHAR(100),
    ADD COLUMN retry_count      INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT uq_payment_idem UNIQUE (idempotency_key),
    ADD CONSTRAINT ck_pay_status CHECK (status IN ('POSTED','FAILED','REVERSED'));

CREATE TABLE payment_allocation (
    allocation_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     BIGINT        NOT NULL REFERENCES premium_payment (payment_id),
    schedule_id    BIGINT        NOT NULL REFERENCES premium_schedule (schedule_id),
    alloc_type     VARCHAR(10)   NOT NULL,   -- PREMIUM, LATE_FEE
    amount         NUMERIC(14,2) NOT NULL
);
CREATE INDEX idx_alloc_payment ON payment_allocation (payment_id);
CREATE INDEX idx_alloc_schedule ON payment_allocation (schedule_id);

CREATE TABLE billing_receipt (
    receipt_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id  BIGINT        NOT NULL UNIQUE REFERENCES premium_payment (payment_id),
    receipt_no  VARCHAR(24)   NOT NULL UNIQUE,
    amount      NUMERIC(14,2) NOT NULL,
    issued_dt   TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE billing_journal (
    journal_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type   VARCHAR(20)  NOT NULL,   -- PREMIUM_BILLED, PAYMENT, LATE_FEE, REFUND, REFUND_PAID, CLAIM_PAYOUT, CLAIM_REVERSAL
    ref_type     VARCHAR(20),
    ref_id       BIGINT,
    policy_id    BIGINT       REFERENCES policy (policy_id),
    description  VARCHAR(200),
    posted_by    VARCHAR(30)  NOT NULL,
    posted_dt    TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_journal_policy ON billing_journal (policy_id);
CREATE INDEX idx_journal_ref ON billing_journal (ref_type, ref_id);

CREATE TABLE billing_journal_line (
    line_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id    BIGINT        NOT NULL REFERENCES billing_journal (journal_id),
    account_code  VARCHAR(12)   NOT NULL,
    dr_cr         VARCHAR(2)    NOT NULL,
    amount        NUMERIC(14,2) NOT NULL,
    CONSTRAINT ck_jl_drcr CHECK (dr_cr IN ('DR','CR')),
    CONSTRAINT ck_jl_account CHECK (account_code IN
        ('CASH','PREM_RECV','PREM_INCOME','FEE_RECV','FEE_INCOME','REFUND_PAY','CLAIM_PAY','SUSPENSE'))
);
CREATE INDEX idx_jl_journal ON billing_journal_line (journal_id);

CREATE TABLE policy_credit_txn (
    credit_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id   BIGINT        NOT NULL REFERENCES policy (policy_id),
    amount      NUMERIC(14,2) NOT NULL,   -- + created, - consumed/refunded
    reason      VARCHAR(100)  NOT NULL,
    ref_type    VARCHAR(20),
    ref_id      BIGINT,
    created_dt  TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_credit_policy ON policy_credit_txn (policy_id);

CREATE TABLE billing_retry_queue (
    retry_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id       BIGINT       NOT NULL REFERENCES premium_payment (payment_id),
    policy_id        BIGINT       NOT NULL REFERENCES policy (policy_id),
    attempt_no       INTEGER      NOT NULL DEFAULT 0,
    max_attempts     INTEGER      NOT NULL DEFAULT 3,
    next_attempt_dt  TIMESTAMP    NOT NULL,
    status           VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    last_error       VARCHAR(200),
    created_dt       TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_retry_status CHECK (status IN ('PENDING','DONE','EXHAUSTED','CANCELLED'))
);
CREATE INDEX idx_retry_due ON billing_retry_queue (status, next_attempt_dt);

CREATE TABLE billing_product_config (
    product_id      BIGINT        PRIMARY KEY REFERENCES insurance_product (product_id),
    late_fee_pct    NUMERIC(6,3)  NOT NULL DEFAULT 2.000,
    late_fee_flat   NUMERIC(14,2) NOT NULL DEFAULT 0,
    grace_days      INTEGER       NOT NULL DEFAULT 30,
    max_retries     INTEGER       NOT NULL DEFAULT 3,
    refund_scale    VARCHAR(10)   NOT NULL DEFAULT 'PRORATA',
    cancel_fee_pct  NUMERIC(6,3)  NOT NULL DEFAULT 10.000,
    CONSTRAINT ck_refund_scale CHECK (refund_scale IN ('PRORATA','SHORTRATE'))
);

CREATE TABLE billing_refund (
    refund_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id        BIGINT        NOT NULL REFERENCES policy (policy_id),
    request_key      VARCHAR(40)   NOT NULL UNIQUE,
    cancellation_id  BIGINT,
    gross_amount     NUMERIC(14,2) NOT NULL,
    fee_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    net_amount       NUMERIC(14,2) NOT NULL,
    method           VARCHAR(10)   NOT NULL,
    status           VARCHAR(10)   NOT NULL DEFAULT 'POSTED',
    created_dt       TIMESTAMP     NOT NULL DEFAULT now(),
    paid_dt          TIMESTAMP,
    CONSTRAINT ck_refund_status CHECK (status IN ('POSTED','PAID','CANCELLED'))
);
CREATE INDEX idx_refund_policy ON billing_refund (policy_id);

CREATE TABLE billing_lapse_log (
    lapse_log_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id     BIGINT       NOT NULL REFERENCES policy (policy_id),
    from_status   VARCHAR(20)  NOT NULL,
    to_status     VARCHAR(20)  NOT NULL,
    as_of_dt      DATE         NOT NULL,
    detail        VARCHAR(200),
    created_dt    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE SEQUENCE receipt_no_seq START 1000;
